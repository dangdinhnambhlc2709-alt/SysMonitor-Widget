    private string _currentCode = "vi";

    public event PropertyChangedEventHandler? PropertyChanged;
    public event Action? LanguageChanged;

    public string CurrentLanguageCode
    {
        get => _currentCode;
        set
        {
            string norm = string.IsNullOrWhiteSpace(value) ? "vi" : value.Trim().ToLowerInvariant();
            if (!_translations.ContainsKey(norm))
                norm = "vi";

            if (_currentCode == norm)
                return;

            _currentCode = norm;
            PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(nameof(CurrentLanguageCode)));
            PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(nameof(FlowDirection)));
            PropertyChanged?.Invoke(this, new PropertyChangedEventArgs("Item[]"));
            LanguageChanged?.Invoke();
        }
    }

    public FlowDirection FlowDirection => _currentCode == "ar" ? FlowDirection.RightToLeft : FlowDirection.LeftToRight;

    public string this[string key] => Get(key);

    public string Get(string key)
    {
        if (string.IsNullOrEmpty(key))
            return string.Empty;
        if (_translations.TryGetValue(_currentCode, out var dict) && dict.TryGetValue(key, out var val))
            return val;
        if (_translations["en"].TryGetValue(key, out var enVal))
            return enVal;
        if (_translations["vi"].TryGetValue(key, out var viVal))
            return viVal;
        return key;
    }

    public string Format(string key, params object[] args)
    {
        string template = Get(key);
        try
        {
            return args is { Length: > 0 } ? string.Format(template, args) : template;
        }
        catch
        {
            return template;
        }
    }

